export const DICT: Record<Lang, Record<Key, string>> = { en, hi, es };

export const hasKey = (k: string): k is Key => k in en;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = DICT[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** BCP-47 tag for the device voice and speech recognition. */
export function speechLang(lang: Lang) {
  const nav = typeof navigator !== "undefined" ? navigator.language : "en-US";
  if (lang === "hi") return "hi-IN";
  if (lang === "es") return nav.startsWith("es") ? nav : "es-ES";
  return nav.startsWith("en") ? nav : "en-US";
}
